package org.androidannotations.ksp.generate;

import org.androidannotations.ksp.AnnotationNames;
import org.androidannotations.ksp.KspAnnotationUtils;
import org.androidannotations.ksp.SharedPrefModel;
import org.androidannotations.ksp.env.RClassIndex;
import org.androidannotations.ksp.handler.SharedPrefHandler;

/**
 * Emits the Java shared-preferences helper described by a {@link SharedPrefModel}, mirroring APT
 * {@code SharedPrefHolder} (helper + static nested {@code Editor_}).
 */
public final class SharedPrefGenerator {

	private static final String API = "org.androidannotations.api.sharedpreferences.";

	private final String resourcePackage;
	private final String rClassName;
	private final RClassIndex rClassIndex;

	public SharedPrefGenerator(String resourcePackage, String rClassName, RClassIndex rClassIndex) {
		this.resourcePackage = resourcePackage;
		this.rClassName = rClassName;
		this.rClassIndex = rClassIndex;
	}

	/** Top-level {@code public final class Name_}. */
	public String generate(SharedPrefModel model) {
		StringBuilder out = new StringBuilder();
		if (model.packageName != null && !model.packageName.isEmpty()) {
			out.append("package ").append(model.packageName).append(";\n\n");
		}
		out.append("/**\n");
		out.append(" * Generated by AndroidAnnotations KSP MVP processor.\n");
		out.append(" */\n");
		out.append("public final class ").append(model.generatedSimpleName()).append(" extends ").append(API).append("SharedPreferencesHelper {\n\n");
		appendBody(out, model, "\t");
		out.append("}\n");
		return out.toString();
	}

	/** Static nested {@code public final static class Name_}, no package line. The caller indents every line. */
	public String generateNested(SharedPrefModel model) {
		StringBuilder out = new StringBuilder();
		out.append("public final static class ").append(model.generatedSimpleName()).append(" extends ").append(API).append("SharedPreferencesHelper {\n\n");
		appendBody(out, model, "");
		out.append("}\n");
		return out.toString();
	}

	private void appendBody(StringBuilder out, SharedPrefModel model, String base) {
		String m = base + "\t";
		String b = base + "\t\t";
		if (model.hasOuterContext) {
			out.append(m).append("private android.content.Context context_;\n\n");
		}
		out.append(m).append("public ").append(model.generatedSimpleName()).append("(android.content.Context context) {\n");
		out.append(b).append("super(").append(superArg(model)).append(");\n");
		if (model.hasOuterContext) {
			out.append(b).append("this.context_ = context;\n");
		}
		out.append(m).append("}\n\n");

		String outerRef = outerRef(model);
		String editorName = model.editorSimpleName();
		out.append(m).append("public ").append(outerRef).append('.').append(editorName).append(" edit() {\n");
		out.append(b).append("return new ").append(outerRef).append('.').append(editorName).append("(getSharedPreferences()");
		if (model.hasEditorContext) {
			out.append(", context_");
		}
		out.append(");\n");
		out.append(m).append("}\n\n");

		if (model.scope == SharedPrefModel.Scope.ACTIVITY || model.scope == SharedPrefModel.Scope.ACTIVITY_DEFAULT) {
			appendGetLocalClassName(out, m, b);
		}

		for (SharedPrefModel.PrefMethod method : model.methods) {
			appendFieldMethod(out, method, m, b);
		}

		out.append(m).append("public final static class ").append(editorName).append(" extends ").append(API).append("EditorHelper<").append(outerRef).append('.').append(editorName).append("> {\n\n");
		if (model.hasEditorContext) {
			out.append(b).append("private android.content.Context context_;\n\n");
		}
		out.append(b).append(editorName).append("(android.content.SharedPreferences sharedPreferences");
		if (model.hasEditorContext) {
			out.append(", android.content.Context context");
		}
		out.append(") {\n");
		out.append(b + "\t").append("super(sharedPreferences);\n");
		if (model.hasEditorContext) {
			out.append(b + "\t").append("this.context_ = context;\n");
		}
		out.append(b).append("}\n\n");
		for (SharedPrefModel.PrefMethod method : model.methods) {
			appendEditorMethod(out, outerRef, editorName, method, b);
		}
		out.append(m).append("}\n");
	}

	/** Generated class reference without the package prefix: {@code Outer_} or {@code Outer_.Nested_}. */
	private static String outerRef(SharedPrefModel model) {
		String qualified = model.generatedQualifiedName();
		if (model.packageName != null && !model.packageName.isEmpty() && qualified.startsWith(model.packageName + ".")) {
			return qualified.substring(model.packageName.length() + 1);
		}
		return qualified;
	}

	private static String superArg(SharedPrefModel model) {
		int mode = model.mode;
		switch (model.scope) {
		case ACTIVITY_DEFAULT:
			return "context.getSharedPreferences(getLocalClassName(context), " + mode + ")";
		case ACTIVITY:
			return "context.getSharedPreferences((getLocalClassName(context)+" + SharedPrefHandler.javaString("_" + model.effectiveName) + "), " + mode + ")";
		case UNIQUE:
			return "context.getSharedPreferences(" + SharedPrefHandler.javaString(model.effectiveName) + ", " + mode + ")";
		case APPLICATION_DEFAULT:
		default:
			return "android.preference.PreferenceManager.getDefaultSharedPreferences(context)";
		}
	}

	private static void appendGetLocalClassName(StringBuilder out, String m, String b) {
		out.append(m).append("private static String getLocalClassName(android.content.Context context) {\n");
		out.append(b).append("String packageName = context.getPackageName();\n");
		out.append(b).append("String className = context.getClass().getName();\n");
		out.append(b).append("int packageLen = packageName.length();\n");
		out.append(b).append("if (((!className.startsWith(packageName))||(className.length()<= packageLen))||(className.charAt(packageLen)!= '.')) {\n");
		out.append(b + "\t").append("return className;\n");
		out.append(b).append("}\n");
		out.append(b).append("return className.substring((packageLen + 1));\n");
		out.append(m).append("}\n\n");
	}

	private void appendFieldMethod(StringBuilder out, SharedPrefModel.PrefMethod method, String m, String b) {
		appendFieldJavadoc(out, method, m);
		out.append(m).append("public ").append(API).append(method.fieldClassSimple).append(' ').append(method.name).append("() {\n");
		out.append(b).append("return ").append(method.helperMethodName).append('(').append(keyExpression(method)).append(", ").append(method.defaultExpr).append(");\n");
		out.append(m).append("}\n\n");
	}

	private void appendEditorMethod(StringBuilder out, String outerRef, String editorName, SharedPrefModel.PrefMethod method, String b) {
		appendEditorJavadoc(out, method, b);
		out.append(b).append("public ").append(API).append(method.editorFieldClassSimple).append('<').append(outerRef).append('.').append(editorName).append("> ").append(method.name).append("() {\n");
		out.append(b + "\t").append("return ").append(method.helperMethodName).append('(').append(keyExpression(method)).append(");\n");
		out.append(b).append("}\n\n");
	}

	private String keyExpression(SharedPrefModel.PrefMethod method) {
		if (method.keyResId == AnnotationNames.RES_DEFAULT) {
			return SharedPrefHandler.javaString(method.name);
		}
		String idRef = KspAnnotationUtils.resExpression(resourcePackage, rClassName == null ? "R" : rClassName, "string", method.name, method.keyResId, "", rClassIndex);
		return "context_.getString(" + idRef + ")";
	}

	/**
	 * APT {@code SharedPrefHolder} javadoc: optional {@code <p><b>Defaults to</b>: ...</p>} line (String values quoted),
	 * the trimmed doc lines, then a blank separator line when either is present, then a standalone {@code @return}
	 * bullet with an indented description. No escaping at all.
	 */
	private static void appendFieldJavadoc(StringBuilder out, SharedPrefModel.PrefMethod method, String indent) {
		boolean hasDefault = method.defaultValueStr != null;
		boolean hasDoc = method.doc != null && !method.doc.isEmpty();
		out.append(indent).append("/**\n");
		if (hasDefault) {
			String shown = "string".equals(method.typeKey) ? "\"" + method.defaultValueStr + "\"" : method.defaultValueStr;
			out.append(indent).append(" * <p><b>Defaults to</b>: ").append(shown).append("</p>\n");
		}
		if (hasDoc) {
			for (String line : method.doc.split("\n", -1)) {
				out.append(indent).append(" *").append(line.isEmpty() ? "" : " " + line).append('\n');
			}
		} else if (hasDefault) {
			// the trailing newline of the Defaults line leaves one empty bullet when no doc follows
			out.append(indent).append(" *\n");
		}
		if (hasDefault || hasDoc) {
			out.append(indent).append(" *\n");
		}
		out.append(indent).append(" * @return\n");
		out.append(indent).append(" *     a {@link ").append(method.fieldClassSimple).append("} instance to retrieve or write the pref value\n");
		out.append(indent).append(" */\n");
	}

	private static void appendEditorJavadoc(StringBuilder out, SharedPrefModel.PrefMethod method, String indent) {
		if (method.doc == null || method.doc.isEmpty()) {
			return;
		}
		out.append(indent).append("/**\n");
		for (String line : method.doc.split("\n", -1)) {
			out.append(indent).append(" *").append(line.isEmpty() ? "" : " " + line).append('\n');
		}
		out.append(indent).append(" */\n");
	}

}






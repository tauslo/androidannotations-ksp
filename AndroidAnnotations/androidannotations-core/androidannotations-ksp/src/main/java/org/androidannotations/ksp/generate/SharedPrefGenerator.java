package org.androidannotations.ksp.generate;

import org.androidannotations.ksp.AnnotationNames;
import org.androidannotations.ksp.KspAnnotationUtils;
import org.androidannotations.ksp.SharedPrefModel;
import org.androidannotations.ksp.env.RClassIndex;
import org.androidannotations.ksp.handler.SharedPrefHandler;

/**
 * Emits the Java shared-preferences helper described by a {@link SharedPrefModel}, mirroring APT
 * {@code SharedPrefHolder} (helper + static {@code Editor_}).
 */
public final class SharedPrefGenerator {

	private static final String API = "org.androidannotations.api.sharedpreferences.";

	private final String resourcePackage;
	private final String rClassName;
	private final RClassIndex rClassIndex;

	public SharedPrefGenerator(String resourcePackage, String rClassName, RClassIndex rClassIndex) {
		this.resourcePackage = resourcePackage;
		this.rClassName = rClassName;
		this.rClassIndex = rClassIndex;
	}

	/** Top-level {@code public final class Name_}. */
	public String generate(SharedPrefModel model) {
		StringBuilder out = new StringBuilder();
		if (model.packageName != null && !model.packageName.isEmpty()) {
			out.append("package ").append(model.packageName).append(";\n\n");
		}
		out.append("/**\n");
		out.append(" * Generated by AndroidAnnotations KSP MVP processor.\n");
		out.append(" */\n");
		out.append("public final class ").append(model.generatedSimpleName())
				.append(" extends ").append(API).append("SharedPreferencesHelper {\n\n");
		appendBody(out, model);
		out.append("}\n");
		return out.toString();
	}

	/** Static nested {@code public static final class Name_}, no package line. Caller indents. */
	public String generateNested(SharedPrefModel model) {
		StringBuilder out = new StringBuilder();
		out.append("public static final class ").append(model.generatedSimpleName())
				.append(" extends ").append(API).append("SharedPreferencesHelper {\n\n");
		appendBody(out, model);
		out.append("}\n");
		return out.toString();
	}

	private void appendBody(StringBuilder out, SharedPrefModel model) {
		if (model.hasOuterContext) {
			out.append("\tprivate android.content.Context context_;\n\n");
		}
		out.append("\tpublic ").append(model.generatedSimpleName()).append("(android.content.Context context) {\n");
		out.append("\t\tsuper(").append(superArg(model)).append(");\n");
		if (model.hasOuterContext) {
			out.append("\t\tthis.context_ = context;\n");
		}
		out.append("\t}\n\n");

		if (model.scope == SharedPrefModel.Scope.ACTIVITY || model.scope == SharedPrefModel.Scope.ACTIVITY_DEFAULT) {
			appendGetLocalClassName(out);
		}

		for (SharedPrefModel.PrefMethod method : model.methods) {
			appendFieldMethod(out, method);
		}

		String editorName = model.editorSimpleName();
		out.append("\tpublic ").append(editorName).append(" edit() {\n");
		out.append("\t\treturn new ").append(editorName).append("(getSharedPreferences()");
		if (model.hasEditorContext) {
			out.append(", context_");
		}
		out.append(");\n");
		out.append("\t}\n\n");

		out.append("\tpublic static final class ").append(editorName)
				.append(" extends ").append(API).append("EditorHelper<").append(editorName).append("> {\n\n");
		if (model.hasEditorContext) {
			out.append("\t\tprivate android.content.Context context_;\n\n");
		}
		out.append("\t\t").append(editorName).append("(android.content.SharedPreferences sharedPreferences");
		if (model.hasEditorContext) {
			out.append(", android.content.Context context");
		}
		out.append(") {\n");
		out.append("\t\t\tsuper(sharedPreferences);\n");
		if (model.hasEditorContext) {
			out.append("\t\t\tthis.context_ = context;\n");
		}
		out.append("\t\t}\n\n");
		for (SharedPrefModel.PrefMethod method : model.methods) {
			appendEditorMethod(out, editorName, method);
		}
		out.append("\t}\n");
	}

	private String superArg(SharedPrefModel model) {
		int mode = model.mode;
		switch (model.scope) {
		case ACTIVITY_DEFAULT:
			return "context.getSharedPreferences(getLocalClassName(context), " + mode + ")";
		case ACTIVITY:
			return "context.getSharedPreferences((getLocalClassName(context)+" + SharedPrefHandler.javaString("_" + model.effectiveName) + "), " + mode + ")";
		case UNIQUE:
			return "context.getSharedPreferences(" + SharedPrefHandler.javaString(model.effectiveName) + ", " + mode + ")";
		case APPLICATION_DEFAULT:
		default:
			return "android.preference.PreferenceManager.getDefaultSharedPreferences(context)";
		}
	}

	private static void appendGetLocalClassName(StringBuilder out) {
		out.append("\tprivate static String getLocalClassName(android.content.Context context) {\n");
		out.append("\t\tString packageName = context.getPackageName();\n");
		out.append("\t\tString className = context.getClass().getName();\n");
		out.append("\t\tint packageLen = packageName.length();\n");
		out.append("\t\tif (!className.startsWith(packageName) || className.length() <= packageLen || className.charAt(packageLen) != '.') {\n");
		out.append("\t\t\treturn className;\n");
		out.append("\t\t}\n");
		out.append("\t\treturn className.substring(packageLen + 1);\n");
		out.append("\t}\n\n");
	}

	private void appendFieldMethod(StringBuilder out, SharedPrefModel.PrefMethod method) {
		appendJavadoc(out, method, true, "\t");
		out.append("\tpublic ").append(API).append(method.fieldClassSimple).append(' ').append(method.name).append("() {\n");
		out.append("\t\treturn ").append(method.helperMethodName).append('(').append(keyExpression(method)).append(", ").append(method.defaultExpr).append(");\n");
		out.append("\t}\n\n");
	}

	private void appendEditorMethod(StringBuilder out, String editorName, SharedPrefModel.PrefMethod method) {
		appendJavadoc(out, method, false, "\t\t");
		out.append("\t\tpublic ").append(API).append(method.editorFieldClassSimple).append('<').append(editorName).append("> ").append(method.name).append("() {\n");
		out.append("\t\t\treturn ").append(method.helperMethodName).append('(').append(keyExpression(method)).append(");\n");
		out.append("\t\t}\n\n");
	}

	private String keyExpression(SharedPrefModel.PrefMethod method) {
		if (method.keyResId == AnnotationNames.RES_DEFAULT) {
			return SharedPrefHandler.javaString(method.name);
		}
		String idRef = KspAnnotationUtils.resExpression(resourcePackage, rClassName == null ? "R" : rClassName, "string", method.name, method.keyResId, "", rClassIndex);
		return "context_.getString(" + idRef + ")";
	}

	private static void appendJavadoc(StringBuilder out, SharedPrefModel.PrefMethod method, boolean includeReturn, String indent) {
		boolean hasDefault = includeReturn && method.defaultValueStr != null;
		boolean hasDoc = method.doc != null && !method.doc.isEmpty();
		if (!includeReturn && !hasDoc) {
			return;
		}
		out.append(indent).append("/**\n");
		if (hasDefault) {
			String shown = "string".equals(method.typeKey) ? "\"" + escapeJavadoc(method.defaultValueStr) + "\"" : escapeJavadoc(method.defaultValueStr);
			out.append(indent).append(" * <p><b>Defaults to</b>: ").append(shown).append("</p>\n");
		}
		if (hasDoc) {
			String[] lines = method.doc.split("\n", -1);
			for (String line : lines) {
				out.append(indent).append(" *");
				if (!line.isEmpty()) {
					out.append(' ').append(escapeJavadoc(line));
				}
				out.append('\n');
			}
		}
		if (includeReturn) {
			out.append(indent).append(" * @return a {@link ").append(method.fieldClassSimple)
					.append("} instance to retrieve or write the pref value\n");
		}
		out.append(indent).append(" */\n");
	}

	private static String escapeJavadoc(String text) {
		return text.replace("*/", "*&#47;");
	}
}

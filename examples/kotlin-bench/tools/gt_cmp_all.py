import re, os, difflib, sys

_here = os.path.dirname(os.path.abspath(__file__))   # .../examples/kotlin-bench/tools
_bench = os.path.dirname(_here)                      # .../examples/kotlin-bench
base_ksp = os.path.join(_bench, "build", "generated", "ksp", "debug", "java", "org", "androidannotations", "bench")
base_gt  = os.path.join(_bench, "build", "generated", "source", "kapt", "debug", "org", "androidannotations", "bench")

def load(p):
    return open(p, encoding="utf-8").read()

KSP_HEADER = "/**\n * Generated by AndroidAnnotations KSP MVP processor.\n */"

IMPORT_RE = re.compile(r"^\s*import\s+(?:static\s+)?([A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)+)\s*;", re.M)

def strip_prepackage(t):
    t = t.replace(KSP_HEADER, "")
    i = t.find("package ")
    if i != -1:
        h = t[:i]
        h = re.sub(r"/\*.*?\*/", "", h, flags=re.S)
        h = re.sub(r"^\s*//.*$", "", h, flags=re.M)
        t = (h if h.strip() else "") + t[i:]
    return t

def build_map(t1, t2):
    imps = set()
    for t in (t1, t2):
        for m in IMPORT_RE.finditer(t):
            imps.add(m.group(1))
    return sorted(imps, key=len, reverse=True)

def apply_map(t, fqs):
    for fqn in fqs:
        simple = fqn.split(".")[-1]
        t = re.sub(r"\b" + re.escape(fqn) + r"(?![A-Za-z0-9_])", simple, t)
    return t

# KNOWN_DEVIATIONS #10: APT declares superNonConfigurationInstance lazily (first access during
# member processing), so its position among holder fields differs from KSP. Purely cosmetic;
# sort the field order of the holder body so both sides compare equal.
def sort_nc_holder_fields(t):
    m = re.search(r"privatestaticclassNonConfigurationInstancesHolder\{", t)
    if not m:
        return t
    start = m.end()
    depth, i = 1, start
    while i < len(t) and depth:
        if t[i] == "{":
            depth += 1
        elif t[i] == "}":
            depth -= 1
        i += 1
    body = t[start:i - 1]
    if not body:
        return t
    fields = sorted(fld for fld in body.split(";") if fld)
    return t[:start] + ";".join(fields) + ";" + t[i - 1:]


def normalize(text, cls, fqs):
    t = strip_prepackage(text)
    lines = [ln for ln in t.splitlines() if not ln.strip().startswith("import ")]
    t = "\n".join(lines)
    t = apply_map(t, fqs)
    t = re.sub(r"\bjava\.lang\.", "", t)  # java.lang.* render-equivalence (see KNOWN_DEVIATIONS)
    t = t.replace("org.androidannotations.gradle.R.", "R.")
    for ty in ("String","int","long","boolean","float","double"):
        t = t.replace("final static " + ty, "static final " + ty)
    t = re.sub(r"OnViewChangedNotifier\.(replaceNotifier|registerOnViewChangedListener)", r"\1", t)
    t = t.replace(cls + "_.FragmentBuilder_", "FragmentBuilder_")
    t = t.replace(cls + "_.IntentBuilder_", "IntentBuilder_")
    t = re.sub(r"\s+", "", t)
    return sort_nc_holder_fields(t)

def regions(a, b):
    sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
    out = []
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag != "equal":
            ca = a[max(0,i1-50):i1] + "<<<" + a[i1:i2] + ">>>" + a[i2:i2+50]
            cb = b[max(0,j1-50):j1] + "<<<" + b[j1:j2] + ">>>" + b[j2:j2+50]
            out.append((tag, ca, cb))
    return out

gt_files = sorted(f for f in os.listdir(base_gt) if f.endswith(".java"))
missing_ksp = [f for f in gt_files if not os.path.exists(os.path.join(base_ksp, f))]
ksp_only = sorted(f for f in os.listdir(base_ksp) if f.endswith(".java") and not os.path.exists(os.path.join(base_gt, f)))
print("GT files:", len(gt_files), " missing in KSP:", missing_ksp, " KSP-only:", ksp_only)

fail = []
for f in gt_files:
    if f in missing_ksp:
        continue
    cls = f[:-5]
    rk = load(os.path.join(base_ksp, f))
    rg = load(os.path.join(base_gt, f))
    fqs = build_map(rk, rg)
    a = normalize(rk, cls, fqs)
    b = normalize(rg, cls, fqs)
    if a == b or a.replace("HashMap","Map") == b.replace("HashMap","Map"):
        continue
    fail.append(f)

print("MISMATCHES:", len(fail))
for f in fail:
    print("  X", f)
if "--detail" in sys.argv and fail:
    n = int(sys.argv[sys.argv.index("--detail")+1]) if len(sys.argv) > sys.argv.index("--detail")+1 else 3
    for f in fail[:n]:
        cls = f[:-5]
        rk = load(os.path.join(base_ksp, f))
        rg = load(os.path.join(base_gt, f))
        fqs = build_map(rk, rg)
        a = normalize(rk, cls, fqs).replace("HashMap","Map")
        b = normalize(rg, cls, fqs).replace("HashMap","Map")
        print("====", f)
        for tag, ca, cb in regions(a, b)[:8]:
            print("  [" + tag + "] KSP:", ca)
            print("  [" + tag + "] GT :", cb)
print("ALL_OK" if not fail else "NOT_ALL_OK")
